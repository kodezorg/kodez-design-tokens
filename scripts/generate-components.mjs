#!/usr/bin/env node
/**
 * scripts/generate-components.mjs
 *
 * Introspects @base-ui/react and generates typed React wrapper components
 * under src/components/. Each wrapper forwards all base-ui props and merges
 * className through cn() so consumers can override token-based defaults.
 *
 * Compound components  (Accordion, Dialog, …) → namespace export
 *   export const Accordion = { Root, Trigger, Panel, … }
 *
 * Simple components  (Button, Input, …) → single named export
 *   export function Button(…)
 *
 * Utilities/hooks  (mergeProps, useRender, …) → plain re-export (no className)
 *
 * Usage:
 *   node scripts/generate-components.mjs
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT    = resolve(__dirname, '..');
const BASE_UI = resolve(ROOT, 'node_modules/@base-ui/react');
const OUT_DIR  = resolve(ROOT, 'src/components');

// ── File helpers ──────────────────────────────────────────────────────────────

function readDts(path) {
  const dtsPath = path.endsWith('.d.ts') ? path : path.replace(/\.js$/, '.d.ts');
  return existsSync(dtsPath) ? readFileSync(dtsPath, 'utf8') : '';
}

// ── Parsers ───────────────────────────────────────────────────────────────────

/** `export * as Foo from` → ["Foo"] */
function parseNamespaceExports(source) {
  return [...source.matchAll(/^export \* as (\w+) from/gm)].map(m => m[1]);
}

/**
 * Named value exports from:
 *   `export { A, B as C, type D } from`
 *   `export declare function Foo`
 *   `export declare const Foo`
 *   `export function/const Foo` (in .d.ts)
 * Returns [{ name, isHook, isUtility }]
 */
function parseValueExports(source) {
  const seen = new Set();
  const results = [];

  function add(name) {
    if (!name || seen.has(name)) return;
    seen.add(name);
    results.push({
      name,
      isHook: name.startsWith('use') && name[3] === name[3].toUpperCase(),
      isUtility: !name[0].match(/[A-Z]/),
    });
  }

  for (const line of source.split('\n')) {
    const t = line.trim();
    if (t.startsWith('export type ')) continue;

    // export { A, B as C, type D } from "..."
    const reExport = t.match(/^export \{([^}]+)\} from/);
    if (reExport) {
      for (const raw of reExport[1].split(',')) {
        const item = raw.trim();
        if (!item || item.startsWith('type ')) continue;
        const parts = item.split(/\s+as\s+/);
        add(parts[parts.length - 1].trim());
      }
      continue;
    }

    // export declare function/const/class/enum Foo
    const decl = t.match(/^export declare (?:function|const|class|enum) (\w+)/);
    if (decl) { add(decl[1]); continue; }

    // export function/const Foo  (in .d.ts without declare)
    const direct = t.match(/^export (?:function|const|class|enum) (\w+)/);
    if (direct) { add(direct[1]); }
  }

  return results;
}

/**
 * Resolve wildcard re-export targets: `export * from "./something.js"`
 * Only plain wildcards, not `export * as`.
 */
function parseWildcardTargets(source) {
  const paths = [];
  for (const line of source.split('\n')) {
    const t = line.trim();
    if (t.startsWith('export type ')) continue;
    const m = t.match(/^export \* from ["']\.\/([^"']+)["']/);
    if (m && !t.includes(' as ')) paths.push(m[1]);
  }
  return [...new Set(paths)];
}

/**
 * Parse index.parts.d.ts → list of { original, alias } for same-package parts.
 * Skips re-exports from parent directories (shared parts from other packages).
 */
function parseParts(source) {
  const parts = [];
  for (const line of source.split('\n')) {
    const t = line.trim();
    if (t.startsWith('export type ')) continue;

    // Only same-package exports: from "./"  (not "../")
    if (!t.includes('from "./"') && !t.match(/from "\.\/[^.]/)) continue;

    // export { Original as Alias } from "./..."
    const aliased = t.match(/^export \{ (\w+) as (\w+) \} from "\.\/([^"]+)"/);
    if (aliased) {
      parts.push({ original: aliased[1], alias: aliased[2] });
      continue;
    }

    // export { Name } from "./..."
    const plain = t.match(/^export \{ (\w+) \} from "\.\/([^"]+)"/);
    if (plain) {
      parts.push({ original: plain[1], alias: plain[1] });
    }
  }
  return parts;
}

// ── Code generators ───────────────────────────────────────────────────────────

const BANNER = [
  '// Generated by scripts/generate-components.mjs — do not edit',
  '// Re-generate: node scripts/generate-components.mjs',
  '',
].join('\n');

/**
 * Generate a compound namespace component file.
 *
 * export const Accordion = { Root, Trigger, Panel, … }
 * React component parts get a className wrapper via cn().
 * Hooks (useXxx) and utilities (camelCase) are re-exported as-is.
 */
function generateCompound(namespace, parts) {
  const isComponent = ({ alias }) =>
    alias[0] === alias[0].toUpperCase() && !alias.startsWith('use');
  const isPassthrough = p => !isComponent(p);

  const componentParts  = parts.filter(isComponent);
  const passthroughParts = parts.filter(isPassthrough);

  const lines = [
    BANNER,
    `import { ${namespace} as _${namespace} } from '@base-ui/react';`,
  ];

  if (componentParts.length > 0) {
    lines.push(
      `import type {`,
      ...componentParts.map(p => `  ${p.original}Props,`),
      `} from '@base-ui/react';`,
      `import { cn } from '../../utils/cn.js';`,
    );
  }

  lines.push('');

  for (const { original, alias } of componentParts) {
    lines.push(
      `function ${alias}({ className, ...props }: ${original}Props) {`,
      `  return <_${namespace}.${alias} className={cn(`,
      `    // TODO: add default token classes here`,
      `    // 'bg-surface-1 text-primary ...',`,
      `    className`,
      `  )} {...props} />;`,
      `}`,
      '',
    );
  }

  // Namespace object: component wrappers + passthrough hooks/utilities
  const componentEntries  = componentParts.map(p => p.alias);
  const passthroughEntries = passthroughParts.map(p => `${p.alias}: _${namespace}.${p.alias}`);
  const allEntries = [...componentEntries, ...passthroughEntries].join(', ');

  lines.push(
    `export const ${namespace} = { ${allEntries} };`,
    '',
  );

  if (componentParts.length > 0) {
    lines.push(
      `export type {`,
      ...componentParts.map(p => `  ${p.original}Props,`),
      `} from '@base-ui/react';`,
      '',
    );
  }

  return lines.join('\n');
}

/**
 * Generate a simple single-component wrapper file.
 *
 * export function Button({ className, ...props }: ButtonProps) { … }
 * Hooks and utilities are re-exported as-is (no className wrapping).
 */
function generateSimple(components, utilityReexports, pkg) {
  const lines = [BANNER];

  const wrappers = components.filter(c => !c.isHook && !c.isUtility);
  const passthrough = components.filter(c => c.isHook || c.isUtility);

  if (wrappers.length > 0) {
    const importNames = wrappers.map(c => `${c.name} as _${c.name}`).join(', ');
    lines.push(
      `import { ${importNames} } from '@base-ui/react';`,
      `import type { ${wrappers.map(c => `${c.name}Props`).join(', ')} } from '@base-ui/react';`,
      `import { cn } from '../../utils/cn.js';`,
      '',
    );

    for (const { name } of wrappers) {
      lines.push(
        `export function ${name}({ className, ...props }: ${name}Props) {`,
        `  return <_${name} className={cn(`,
        `    // TODO: add default token classes here`,
        `    // 'inline-flex items-center bg-accent text-inverse ...',`,
        `    className`,
        `  )} {...props} />;`,
        `}`,
        '',
      );
    }
  }

  if (passthrough.length > 0) {
    lines.push(
      `export { ${passthrough.map(c => c.name).join(', ')} } from '@base-ui/react';`,
      '',
    );
  }

  if (utilityReexports.length > 0) {
    lines.push(
      `export { ${utilityReexports.join(', ')} } from '@base-ui/react';`,
      '',
    );
  }

  lines.push(`export type * from '@base-ui/react/${pkg}';`, '');

  return lines.join('\n');
}

// ── Discover packages ─────────────────────────────────────────────────────────

const SKIP = new Set(['types', 'floating-ui-react', 'internals', 'utils']);

const mainIndex = readDts(resolve(BASE_UI, 'index.d.ts'));
const packages = [...mainIndex.matchAll(/^export \* from "\.\/([^/]+)\/index\.js";/gm)]
  .map(m => m[1])
  .filter(pkg => !SKIP.has(pkg));

// ── Generate ──────────────────────────────────────────────────────────────────

mkdirSync(OUT_DIR, { recursive: true });

const barrelPkgs = [];
let compoundCount = 0;
let simpleCount = 0;

for (const pkg of packages) {
  const pkgDir   = resolve(BASE_UI, pkg);
  const indexSrc = readDts(resolve(pkgDir, 'index.d.ts'));

  const outDir = resolve(OUT_DIR, pkg);
  mkdirSync(outDir, { recursive: true });

  // ── Compound component? ───────────────────────────────────────────────────
  const namespaces = parseNamespaceExports(indexSrc);

  if (namespaces.length > 0) {
    const namespace = namespaces[0];
    const partsSrc  = readDts(resolve(pkgDir, 'index.parts.d.ts'));
    const parts     = parseParts(partsSrc);

    if (parts.length > 0) {
      const content = generateCompound(namespace, parts);
      writeFileSync(resolve(outDir, 'index.tsx'), content);
      barrelPkgs.push(pkg);
      compoundCount++;
      console.log(`  ✓  ${pkg}/index.tsx  [${namespace}: ${parts.map(p => p.alias).join(', ')}]`);
      continue;
    }
  }

  // ── Simple component / utility ─────────────────────────────────────────────
  let valueExports = parseValueExports(indexSrc);

  // Chase wildcard re-exports (e.g. merge-props → mergeProps.d.ts)
  for (const target of parseWildcardTargets(indexSrc)) {
    const inner = readDts(resolve(pkgDir, target));
    valueExports.push(...parseValueExports(inner));
  }

  // Deduplicate preserving order
  const seen = new Set();
  valueExports = valueExports.filter(e => seen.has(e.name) ? false : (seen.add(e.name), true));

  const content = generateSimple(valueExports, [], pkg);
  writeFileSync(resolve(outDir, 'index.tsx'), content);
  barrelPkgs.push(pkg);
  simpleCount++;
  console.log(`  ✓  ${pkg}/index.tsx  [${valueExports.map(e => e.name).join(', ') || 'types only'}]`);
}

// ── Barrel ────────────────────────────────────────────────────────────────────

const barrel = [
  '// Generated by scripts/generate-components.mjs — do not edit',
  '// Re-generate: node scripts/generate-components.mjs',
  '',
  ...barrelPkgs.map(pkg => `export * from './${pkg}/index.js';`),
  '',
  "export { cn } from '../utils/cn.js';",
  '',
].join('\n');

writeFileSync(resolve(OUT_DIR, 'index.ts'), barrel);

console.log(`
  ✓  src/components/index.ts
     ${compoundCount} compound  +  ${simpleCount} simple  =  ${packages.length} total

  Next: add to src/index.ts →  export * from './components/index.js';
`);
